/* Distinct regions covered, derived so it always matches the
   dataset above rather than being maintained twice. */
export const regions = [
  "All",
  ...Array.from(new Set(hospitals.map((h) => h.region))).sort(),
];

/* Quick national-coverage stats used by the "health centres in
   Tanzania" summary shown on the Home and Hospitals pages. */
export function getHospitalStats() {
  const totalRegions = new Set(hospitals.map((h) => h.region)).size;
  const homeServiceCount = hospitals.filter((h) => h.homeService).length;
  const priorityCount = hospitals.filter((h) => h.category === "priority").length;

  return {
    total: hospitals.length,
    totalRegions,
    homeServiceCount,
    priorityCount,
  };
}
